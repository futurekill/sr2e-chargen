/**
 * Writes the textures' CSS and the first-paint script from their sources (docs/PLAN-textures.md):
 *   client/src/textures.css  ← tools/textures.mjs (the CSS) × shared/themes.mjs (which keys exist)
 *   client/public/boot.js    ← shared/themes.mjs (the themes, their keys and defaults, for the head script)
 * `npm run gen:textures`; test/textures.test.mjs fails when either file is out of date.
 */
import { writeFileSync } from "node:fs";
import { THEMES as CSS } from "./textures.mjs";
import { THEME_KEYS, TEXTURES, DEFAULT_TEXTURE } from "../shared/themes.mjs";

export function texturesCss() {
  const rules = [];
  for (const theme of THEME_KEYS) for (const { key } of TEXTURES[theme]) {
    const css = CSS[theme]?.options.find(o => o.key === key)?.css;
    if (!css) throw new Error(`no CSS for ${theme}/${key} in tools/textures.mjs`);
    rules.push(`:root[data-theme="${theme}"][data-texture="${key}"] { ${css} }`);
  }
  return `/* GENERATED by tools/gen-textures.mjs from tools/textures.mjs — do not edit (docs/PLAN-textures.md). */
${rules.join("\n")}
/* High contrast (forced colours): the system's plain background, never a texture. */
@media (forced-colors: active) { :root { background-image: none !important; } }
`;
}
export function bootJs() {
  const known = Object.fromEntries(THEME_KEYS.map(t => [t, TEXTURES[t].map(x => x.key)]));
  return `/* GENERATED by tools/gen-textures.mjs — do not edit. The remembered theme and texture, set before the first paint
   (docs/PLAN-textures.md 4); the app's own code checks them again against the account. */
(function () {
  var known = ${JSON.stringify(known)}, defaults = ${JSON.stringify(DEFAULT_TEXTURE)}, first = ${JSON.stringify(THEME_KEYS[0])};
  var theme = first, texture = null, root = document.documentElement;
  try { theme = localStorage.getItem("theme"); texture = localStorage.getItem("texture"); } catch (e) { /* private mode */ }
  var own = function (o, k) { return typeof k === "string" && Object.prototype.hasOwnProperty.call(o, k); };
  if (!own(known, theme)) theme = first;   // never an inherited name (constructor, __proto__…: code review r1 #2)
  if (texture !== "none" && known[theme].indexOf(texture) < 0) texture = defaults[theme];
  root.setAttribute("data-theme", theme);
  root.setAttribute("data-texture", texture);
})();
`;
}
if (import.meta.url === `file://${process.argv[1]}`) {
  const root = new URL("../", import.meta.url);
  writeFileSync(new URL("client/src/textures.css", root), texturesCss());
  writeFileSync(new URL("client/public/boot.js", root), bootJs());
  console.log("wrote client/src/textures.css and client/public/boot.js");
}
